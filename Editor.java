    private void menuabrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuabrirActionPerformed
        // 1. Crear el explorador de archivos
    javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
    
    // 2. Filtrar para que solo muestre archivos de texto (.txt)
    javax.swing.filechooser.FileNameExtensionFilter filtro = 
            new javax.swing.filechooser.FileNameExtensionFilter("Archivos de Texto (*.txt)", "txt");
    selector.setFileFilter(filtro);

    // 3. Abrir la ventana de diálogo
    int resultado = selector.showOpenDialog(this);

    // 4. Si el usuario selecciona un archivo y presiona "Abrir"
    if (resultado == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File archivo = selector.getSelectedFile();
        
        // Leer el contenido del archivo e insertarlo en el jEditor
        try (java.io.BufferedReader lector = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
            jEditor.read(lector, null); // Método nativo de Swing para cargar texto en componentes
        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                    "Error al abrir el archivo: " + ex.getMessage(), 
                    "Error", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_menuabrirActionPerformed

    private void menuguardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuguardarActionPerformed
      javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
    
    // Filtro para mostrar/guardar como .txt
    javax.swing.filechooser.FileNameExtensionFilter filtro = 
            new javax.swing.filechooser.FileNameExtensionFilter("Archivos de Texto (*.txt)", "txt");
    selector.setFileFilter(filtro);

    // Muestra la ventana en modo Guardar
    int resultado = selector.showSaveDialog(this);

    if (resultado == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File archivo = selector.getSelectedFile();

        // Si el usuario no escribió ".txt" al final, se lo agregamos automáticamente
        if (!archivo.getName().toLowerCase().endsWith(".txt")) {
            archivo = new java.io.File(archivo.getAbsolutePath() + ".txt");
        }

        // Escribir el contenido del jEditor en el archivo
        try (java.io.BufferedWriter escritor = new java.io.BufferedWriter(new java.io.FileWriter(archivo))) {
            jEditor.write(escritor); // Método nativo para exportar el texto
            javax.swing.JOptionPane.showMessageDialog(this, "Archivo guardado con éxito.");
        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                    "Error al guardar el archivo: " + ex.getMessage(), 
                    "Error", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_menuguardarActionPerformed

    private void menunuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menunuevoActionPerformed
       // Si el editor ya tiene texto, podemos pedir confirmación antes de borrar
    if (!jEditor.getText().trim().isEmpty()) {
        int respuesta = javax.swing.JOptionPane.showConfirmDialog(
                this, 
                "¿Deseas crear un nuevo documento? Se perderán los cambios no guardados.", 
                "Nuevo Documento", 
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
            jEditor.setText(""); // Limpia el editor
        }
    } else {
        jEditor.setText(""); // Si ya estaba vacío, solo reinicia
    }
    }//GEN-LAST:event_menunuevoActionPerformed

