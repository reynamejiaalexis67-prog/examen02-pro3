    private void btnnegritaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnnegritaActionPerformed
   int inicio = jEditor.getSelectionStart();
    int fin = jEditor.getSelectionEnd();
    int longitud = fin - inicio;

    if (longitud > 0) {
        SimpleAttributeSet estilo = new SimpleAttributeSet();
        StyleConstants.setBold(estilo, true);

        // Convertimos el documento de JEditorPane a StyledDocument (Casteo)
        if (jEditor.getDocument() instanceof StyledDocument) {
            StyledDocument doc = (StyledDocument) jEditor.getDocument();
            doc.setCharacterAttributes(inicio, longitud, estilo, false);
        }
    }
    }//GEN-LAST:event_btnnegritaActionPerformed

